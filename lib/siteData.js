export function getProductBySlug(slug) {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getCategoryBySlug(slug) {
  return CATEGORIES.find((c) => c.slug === slug);
}

export function getCategoryProducts(categorySlug, subcategorySlug) {
  return PRODUCTS.filter((p) => {
    if (p.category !== categorySlug) return false;
    if (subcategorySlug && p.subcategory !== subcategorySlug) return false;
    return true;
  });
}

export function sortProducts(products, sort) {
  const list = [...products];
  switch (sort) {
    case "price_asc":
      return list.sort((a, b) => a.sp - b.sp);
    case "price_desc":
      return list.sort((a, b) => b.sp - a.sp);
    case "discount":
      return list.sort((a, b) => (b.mrp - b.sp) - (a.mrp - a.sp));
    default:
      return list;
  }
}

export function getRelatedProducts(product, limit = 4) {
  return PRODUCTS.filter((p) => p.slug !== product.slug).slice(0, limit);
}

